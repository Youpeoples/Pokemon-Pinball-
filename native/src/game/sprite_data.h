/*=============================================================================
 * Sprite Data Loader
 * Translated from LoadSpriteData (home.asm:1929)
 *
 * Reads 4-byte OAM entries {y, x, tile, attr} from a raw data array,
 * adds offset_y to y and offset_x to x (matching the ASM's `add c` / `add b`),
 * and writes them to sprite_buffer[].  Stops at 0x80 terminator or buffer full.
 *===========================================================================*/
static inline void load_sprite_data(GameState *state, const uint8_t *data,
                                     uint8_t offset_y, uint8_t offset_x) {
    while (*data != 0x80 && state->sprite_buffer_size < GBC_OAM_ENTRIES) {
        OAMEntry *entry = &state->sprite_buffer[state->sprite_buffer_size];
        entry->y = (uint8_t)(data[0] + offset_y);
        entry->x = (uint8_t)(data[1] + offset_x);
        entry->tile = data[2];
        entry->attr = data[3];
        state->sprite_buffer_size++;
        data += 4;
    }
}

/*=============================================================================
 * Sprite Animation Frame
 * Used by animation tables: {pointer to sprite data, frame duration}.
 * Terminator: {NULL/any, 0} (duration == 0 marks end of animation).
 *===========================================================================*/
typedef struct {
    const uint8_t *sprite_data;  /* NULL = skip loading (e.g. pikachu eyes open) */
    uint8_t duration;
} SpriteAnimFrame;

